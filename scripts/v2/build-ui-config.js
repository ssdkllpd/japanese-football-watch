'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'../..');
function buildConfig(apiBase) {
  if (apiBase) {
    const url = new URL(apiBase);
    if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.pathname !== '/') throw new Error('Public API base must be an HTTPS origin');
    apiBase = url.origin;
  }
  const scope = JSON.parse(fs.readFileSync(path.join(root,'config/competition-scope-v1.json'),'utf8'));
  const legacy = JSON.parse(fs.readFileSync(path.join(root,'config/api-football-existing-results.json'),'utf8'));
  const competitionAliases = Object.fromEntries(Object.entries(legacy.competitionIds).map(([label,id])=>[label,`af:competition:${id}`]));
  for (const item of scope.trackingLeagues) competitionAliases[item.label] = item.id;
  return `// Generated by scripts/v2/build-ui-config.js; public settings only.\nwindow.FOOTBALL_V2_CONFIG = Object.freeze(${JSON.stringify({apiBase:apiBase || null,previewOrigins:['http://localhost:8787','http://127.0.0.1:8787'],trackingEnabled:false,attentionEnabled:false,scope,competitionAliases},null,2)});\n`;
}
if (require.main === module) fs.writeFileSync(process.argv[2] || path.join(root,'app-v2-config.js'),buildConfig(process.env.FOOTBALL_V2_PUBLIC_API_BASE));
module.exports = { buildConfig };
