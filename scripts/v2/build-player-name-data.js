'use strict';
const fs = require('node:fs');
const path = require('node:path');
const evidence = require('../../config/d1-major-league-snapshot-20260908.json');

function build(source) {
  if (source.snapshotId !== evidence.snapshotId || source.archiveSha256 !== evidence.archiveSha256) {
    throw new Error('Name source must come from the pinned verified snapshot.');
  }
  const players = new Map();
  for (const row of source.players) {
    if (!Number.isSafeInteger(row.playerId) || row.playerId <= 0 || !row.name?.trim()) throw new Error('Invalid player identity or display name.');
    const full = row.firstname?.trim() && row.lastname?.trim() ? `${row.firstname.trim()} ${row.lastname.trim()}` : null;
    const value = [row.name.trim(), full];
    if (players.has(row.playerId) && JSON.stringify(players.get(row.playerId)) !== JSON.stringify(value)) throw new Error(`Conflicting names for ${row.playerId}.`);
    players.set(row.playerId, value);
  }
  return {
    snapshotId: source.snapshotId,
    archiveSha256: source.archiveSha256,
    schemaVersion: 'jfw-player-display-names/1',
    players: Object.fromEntries([...players].sort(([a], [b]) => a - b).map(([id, value]) => [`af:player:${id}`, value])),
  };
}

function serialize(data) {
  return '// Provider display labels and name parts from the pinned saved 2026-09-08 snapshot.\n'
    + '// Generated by scripts/v2/build-player-name-data.js; no names are inferred.\n'
    + "(function(root,factory){const data=factory();if(typeof module==='object'&&module.exports)module.exports=data;if(root)root.JFWPlayerNameData=data;})(typeof globalThis!=='undefined'?globalThis:this,()=> ("
    + JSON.stringify(data) + '));\n';
}

if (require.main === module) {
  if (!process.argv[2]) throw new Error('Usage: node scripts/v2/build-player-name-data.js VERIFIED_AUDIT_REPORT [OUTPUT]');
  const source = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  fs.writeFileSync(process.argv[3] || path.resolve(__dirname, '../../player-name-data.js'), serialize(build(source)));
}
module.exports = { build, serialize };
